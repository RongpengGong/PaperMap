"""Field hub pages (knowledge-map nodes): fields/<slug>.md.

Every section is rebuilt deterministically from the database, so adding a
paper only adds its entries (no LLM rewrites the page) and reruns are
idempotent. The user's block between USER_BEGIN/USER_END is preserved.
"""

from __future__ import annotations

import json
import re
from collections import Counter
from datetime import date
from pathlib import Path

import yaml

from .kb_writer import USER_BEGIN, USER_END, read_user_section
from .registry import Registry
from .taxonomy import Taxonomy

H = {
    "zh": {
        "overview": "概述", "papers": "代表文献", "tools": "常用方法与工具",
        "progress": "方法变体与新进展", "disputes": "争议 / 不一致的结论",
        "cross_m": "与其他学科的交叉（主题）", "cross_t": "与研究方法的交叉",
        "notes": "我的笔记", "notes_hint": "（在这里写你自己的笔记，程序永远不会改动这一块。）",
        "empty": "（暂无）", "primary": "主要方法",
        "disputes_todo": "（论文积累到一定数量后，由「整合」步骤对比不同论文的结论生成。）",
        "retired": "⚠️ 该类别已从分类表中移除，仅保留历史记录。",
        "count": "篇",
    },
    "en": {
        "overview": "Overview", "papers": "Key papers", "tools": "Common methods & tools",
        "progress": "Method variants & progress", "disputes": "Disagreements / conflicting results",
        "cross_m": "Cross-links (topics)", "cross_t": "Cross-links (methods)",
        "notes": "My notes", "notes_hint": "(Your own notes; PaperMap never changes this block.)",
        "empty": "(none yet)", "primary": "primary method",
        "disputes_todo": "(Generated by the consolidation step once enough papers accumulate.)",
        "retired": "⚠️ This category was removed from the taxonomy; kept for history.",
        "count": "papers",
    },
}


def tool_name(raw: str) -> str:
    """'CellPhoneDB v5.0.0（xx）' -> 'CellPhoneDB' (for counting across papers)."""
    t = re.split(r"[（(]", raw, maxsplit=1)[0]
    t = re.sub(r"\s+v?\d+(\.\d+)*\w*$", "", t.strip())
    return t.strip(" ,;")


def field_rel_path(slug: str) -> str:
    return f"fields/{slug}.md"


def paper_link(row) -> str:
    target = (row["kb_path"] or "").removesuffix(".md")
    author = row["first_author"] or "?"
    label = f"{author} {row['year'] or ''} · {row['journal'] or ''}".strip(" ·")
    return f"[[{target}|{label}]]" if target else label


def field_link(slug: str, name: str) -> str:
    return f"[[fields/{slug}|{name}]]"


def render_field(registry: Registry, field, taxonomy: Taxonomy | None, language: str,
                 user_section: str | None, has_handbook: bool = False) -> str:
    h = H["en" if language == "en" else "zh"]
    name_col = "name_en" if language == "en" else "name_zh"
    rows = registry.field_paper_rows(field["id"])
    cat = taxonomy.by_slug.get(field["slug"]) if taxonomy else None

    front = {
        "slug": field["slug"], "name_zh": field["name_zh"], "name_en": field["name_en"],
        "axis": field["axis"], "status": field["status"], "paper_count": len(rows),
        "updated": date.today().isoformat(),
    }
    out = ["---", yaml.safe_dump(front, allow_unicode=True, sort_keys=False, width=10**6).strip(), "---", ""]
    other = field["name_en"] if language != "en" else field["name_zh"]
    out += [f"# {field[name_col]}（{other}）" if language != "en" else f"# {field[name_col]} ({other})", ""]
    if field["status"] == "retired":
        out += [h["retired"], ""]

    def section(title: str, lines: list[str]) -> None:
        out.extend([f"## {title}", "", *(lines or [h["empty"]]), ""])

    desc = (cat.description if cat else field["description"]) or ""
    syn = ", ".join(cat.synonyms) if cat and cat.synonyms else ""
    hb = ([""] + [f"📘 [[handbooks/{field['slug']}|{'Handbook' if language == 'en' else '学习手册'}]]"]) if has_handbook else []
    section(h["overview"], [desc] + (["", f"*{syn}*"] if syn else []) + hb)
    out += [f"## {h['notes']}", "", USER_BEGIN, user_section if user_section is not None else h["notes_hint"], USER_END, ""]

    # Key papers, newest first
    lines = []
    for r in rows:
        card = json.loads(r["card_json"] or "{}")
        star = " ★" if r["is_primary"] else ""
        one = card.get("one_sentence", "")
        lines.append(f"- {r['year'] or ''} {paper_link(r)}{star} — {one}".rstrip(" —"))
    section(f"{h['papers']}（{len(rows)} {h['count']}）" if language != "en" else f"{h['papers']} ({len(rows)})", lines)

    # Tools: counted across papers in this field
    tools: Counter[str] = Counter()
    display: dict[str, str] = {}
    for r in rows:
        keys = set()
        for t in json.loads(r["card_json"] or "{}").get("tools", []):
            name = tool_name(t)
            if name:
                keys.add(name.lower())
                display.setdefault(name.lower(), name)
        tools.update(keys)
    section(h["tools"], [", ".join(f"`{display[t]}` ×{n}" if n > 1 else f"`{display[t]}`"
                                   for t, n in tools.most_common(40))] if tools else [])

    if field["axis"] == "method":
        section(h["progress"], [f"- {r['year'] or ''} {paper_link(r)}: {r['note']}" for r in rows if r["note"]])
    section(h["disputes"], [h["disputes_todo"]])

    # Cross-links: co-assigned fields of the other axis (or same axis for topics)
    co: Counter[tuple[str, str]] = Counter()
    for r in rows:
        for fr in registry.paper_field_rows(r["paper_id"]):
            if fr["slug"] != field["slug"] and fr["status"] == "accepted":
                if field["axis"] == "method" and fr["axis"] != "topic":
                    continue
                co[(fr["slug"], fr[name_col])] += 1
    title = h["cross_m"] if field["axis"] == "method" else h["cross_t"]
    section(title, [f"- {field_link(s, n)} ×{c}" for (s, n), c in co.most_common()])
    return "\n".join(out).rstrip() + "\n"


def write_field(knowledge_dir: Path, registry: Registry, field, taxonomy: Taxonomy | None,
                language: str) -> str:
    rel = field_rel_path(field["slug"])
    path = knowledge_dir / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    has_hb = (knowledge_dir / "handbooks" / f"{field['slug']}.md").exists()
    text = render_field(registry, field, taxonomy, language, read_user_section(path), has_hb)
    tmp = path.with_suffix(".md.tmp")
    tmp.write_text(text, "utf-8")
    tmp.replace(path)
    return rel


def write_fields(knowledge_dir: Path, registry: Registry, taxonomy: Taxonomy | None, language: str,
                 slugs: set[str] | None = None) -> list[str]:
    """(Re)write hub pages for the given slugs, or all active/used fields."""
    rows = registry.query(
        "SELECT * FROM fields WHERE status IN ('active','retired') ORDER BY axis, sort_order"
    )
    written = []
    for f in rows:
        if slugs is not None and f["slug"] not in slugs:
            continue
        used = registry.one("SELECT 1 FROM paper_fields WHERE field_id=? LIMIT 1", (f["id"],))
        if f["status"] == "retired" and not used:
            continue
        written.append(write_field(knowledge_dir, registry, f, taxonomy, language))
    return written
